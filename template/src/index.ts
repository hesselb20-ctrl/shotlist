import { cpSync, existsSync, mkdirSync, readdirSync, renameSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import type { Shot, Shotlist } from '@shotlist/schema';

export const REMOTION_VERSION = '4.0.543';

export interface ExportOptions {
  /** Package name of the generated project. Defaults to the directory name. */
  name?: string;
  /** Write into a directory that already contains files. */
  force?: boolean;
}

const scaffoldDir = fileURLToPath(new URL('../scaffold', import.meta.url));

/**
 * Writes a Remotion project to outDir: the static scaffold plus the files that depend on the
 * shot list (Main.tsx with one <Sequence> per shot, slots.tsx, shotlist.json, package.json, README).
 * Returns the paths of the generated files, relative to outDir.
 */
export function exportTemplate(shotlist: Shotlist, outDir: string, options: ExportOptions = {}): string[] {
  if (existsSync(outDir) && readdirSync(outDir).length > 0 && !options.force) {
    throw new Error(`${outDir} already exists and is not empty. Pick another directory or pass --force.`);
  }
  mkdirSync(path.join(outDir, 'src'), { recursive: true });
  cpSync(scaffoldDir, outDir, { recursive: true });
  // npm strips .gitignore from published packages, so the scaffold stores it without the dot.
  renameSync(path.join(outDir, 'gitignore'), path.join(outDir, '.gitignore'));

  const name = (options.name ?? path.basename(path.resolve(outDir)))
    .toLowerCase()
    .replace(/[^a-z0-9-_.]+/g, '-')
    .replace(/^[-_.]+/, '') || 'shotlist-template';

  const generated: Record<string, string> = {
    'package.json': packageJson(name),
    'README.md': readme(name, shotlist),
    'src/shotlist.json': JSON.stringify(shotlist, null, 2) + '\n',
    'src/Main.tsx': mainTsx(shotlist),
    'src/slots.tsx': slotsTsx(shotlist),
  };
  for (const [file, content] of Object.entries(generated)) {
    writeFileSync(path.join(outDir, file), content);
  }
  return [...listFiles(scaffoldDir).map((f) => (f === 'gitignore' ? '.gitignore' : f)), ...Object.keys(generated)].sort();
}

function listFiles(dir: string, base = ''): string[] {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const rel = base ? `${base}/${entry.name}` : entry.name;
    return entry.isDirectory() ? listFiles(path.join(dir, entry.name), rel) : [rel];
  });
}

const sec = (n: number) => n.toFixed(2);

function packageJson(name: string): string {
  return (
    JSON.stringify(
      {
        name,
        version: '0.1.0',
        private: true,
        scripts: {
          dev: 'remotion studio',
          render: 'remotion render Main out/video.mp4',
          still: 'remotion still Main out/frame.png --frame=0',
          typecheck: 'tsc --noEmit',
        },
        dependencies: {
          '@remotion/cli': REMOTION_VERSION,
          react: '^19.0.0',
          'react-dom': '^19.0.0',
          remotion: REMOTION_VERSION,
        },
        devDependencies: {
          '@types/react': '^19.0.0',
          typescript: '^5.9.0',
        },
      },
      null,
      2,
    ) + '\n'
  );
}

function mainTsx(s: Shotlist): string {
  const sequences = s.shots
    .map(
      (shot: Shot) =>
        `      {/* ${shot.id} · ${shot.role} · ${sec(shot.startSec)}s to ${sec(shot.endSec)}s${
          shot.index > 0 ? ` · cut ${shot.cutOnBeat ? 'on' : 'off'} the beat` : ''
        } */}\n` +
        `      <Sequence name="${shot.id} ${shot.role}" from={${shot.startFrame}} durationInFrames={${shot.durationFrames}}>\n` +
        `        <Slot shot={shots[${shot.index}]} fill={slots.${shot.id}} />\n` +
        `      </Sequence>`,
    )
    .join('\n');

  return `import React from 'react';
import {AbsoluteFill, Audio, Sequence, staticFile} from 'remotion';
import {Captions} from './Captions';
import {shots} from './data';
import {Slot} from './Slot';
import {audio, slots} from './slots';
import {theme} from './theme';

// Generated by shotlist from ${s.source.file}.
// ${s.shots.length} shots, ${s.source.durationFrames} frames at ${s.source.fps} fps. The timings below match the source
// frame for frame: change what is inside a slot (src/slots.tsx), not when it starts.
export const Main: React.FC = () => {
  return (
    <AbsoluteFill style={{backgroundColor: theme.bg}}>
${sequences}
      <Captions />
      {audio ? <Audio src={/^https?:/.test(audio) ? audio : staticFile(audio)} /> : null}
    </AbsoluteFill>
  );
};
`;
}

function slotsTsx(s: Shotlist): string {
  const entries = s.shots
    .map(
      (shot) =>
        `  // ${shot.id} · ${shot.role} · ${shot.durationFrames} frames (${sec(shot.endSec - shot.startSec)}s) · wants ${shot.slot.type}\n` +
        `  // ${shot.slot.hint.replace(/\s+/g, ' ')}\n` +
        `  ${shot.id}: {kind: 'placeholder'},`,
    )
    .join('\n');

  return `import type {SlotFill} from './types';

/**
 * Fill the slots. Each key is one shot of the source edit; when it plays is fixed in Main.tsx.
 *
 *   {kind: 'placeholder'}                                   labelled card (the default)
 *   {kind: 'video', src: 'clip.mp4', startFrom: 0}          file in public/ or a URL; startFrom is in frames
 *   {kind: 'image', src: 'photo.jpg'}                       file in public/ or a URL
 *   {kind: 'text', text: 'Your line', background: '#101010', color: '#ffffff'}
 *   {kind: 'component', component: MyScene}                 any React component, receives {shot}
 */
export const slots: Record<string, SlotFill> = {
${entries}
};

/** Music or voice-over: a file in public/ or a URL. ${
    s.beats.bpm ? `The source ran at about ${s.beats.bpm} BPM, so a track at that tempo keeps the cuts on the beat.` : 'null plays no audio.'
  } */
export const audio: string | null = null;
`;
}

function readme(name: string, s: Shotlist): string {
  const rows = s.shots
    .map(
      (shot) =>
        `| \`${shot.id}\` | ${shot.role} | ${sec(shot.startSec)}s | ${sec(shot.endSec - shot.startSec)}s | ${shot.durationFrames} | ${shot.slot.type} | ${shot.slot.hint.replace(/\|/g, '/')} |`,
    )
    .join('\n');

  return `# ${name}

A Remotion template generated by [shotlist](https://github.com/hesselb20-ctrl/shotlist) from \`${s.source.file}\`:
${s.shots.length} shots, ${s.source.durationFrames} frames at ${s.source.fps} fps, ${s.source.width}x${s.source.height}.

The edit is kept, the content is yours: every shot of the source is a \`<Sequence>\` with the same start frame
and length, and a slot you fill with your own video, image, text or component.

## Use it

\`\`\`bash
npm install
npm run dev      # Remotion Studio: scrub the timeline, see every slot
npm run render   # writes out/video.mp4
\`\`\`

1. Put your assets in \`public/\`.
2. Open \`src/slots.tsx\` and replace each \`{kind: 'placeholder'}\`.
3. Set \`audio\` in the same file if you have a track.

## Slots

| Slot | Role | Starts | Length | Frames | Wants | Hint |
|---|---|---|---|---|---|---|
${rows}

## Files

- \`src/Main.tsx\`: one \`<Sequence>\` per shot. Generated; edit only if you want to change the timing.
- \`src/slots.tsx\`: what goes in each slot. This is the file you edit.
- \`src/shotlist.json\`: the full analysis (beats, captions, pacing) the template was generated from.
- \`src/Slot.tsx\`, \`src/Captions.tsx\`, \`src/theme.ts\`: rendering. Restyle freely.

Remotion has its own licence: free for individuals and small teams, paid for larger companies.
See https://remotion.dev/license.
`;
}
